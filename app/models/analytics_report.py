"""
Analytics Report Model
----------------------
Simple reports generated by researchers from aggregated user data.
"""

from app import db


class AnalyticsReport(db.Model):
    """Analytics_report table - researcher-generated reports."""

    __tablename__ = 'analytics_report'

    id = db.Column(db.Integer, primary_key=True)
    researcher_id = db.Column(db.Integer, db.ForeignKey('user.id'), nullable=False)
    report_type = db.Column(db.String(50), nullable=False)
    title = db.Column(db.String(255), nullable=False)
    content = db.Column(db.Text)
    generated_at = db.Column(db.DateTime, server_default=db.func.now())

    # Relationships
    researcher = db.relationship('User')

    def __repr__(self):
        return f'<AnalyticsReport {self.title[:30]}>'
